def add_assignments():
    """批量添加作业题目到数据库"""
    app = create_app('development')
    
    with app.app_context():
        # 创建一个管理员ID，用于记录日志
        admin_id = "admin"  # 这里可以根据实际情况修改
        count = 0
        
        for assignment_data in ASSIGNMENTS:
            # 检查作业ID是否已存在
            existing = Assignment.query.get(assignment_data["id"])
            if existing:
                print(f"作业ID {assignment_data['id']} 已存在，跳过")
                continue
                
            # 创建新作业
            new_assignment = Assignment(
                id=assignment_data["id"],
                title=assignment_data["title"],
                description=assignment_data["description"],
                total_score=0,
                average_score=0.0,
                count=0,
                created_time=datetime.datetime.utcnow()
            )
            
            try:
                db.session.add(new_assignment)
                db.session.commit()
                
                # 添加系统日志
                SystemLog.add_log(
                    log_type='添加作业',
                    content=f'系统批量导入了新作业：{new_assignment.title} (ID: {new_assignment.id})',
                    user_id=admin_id,
                    icon='bi bi-file-earmark-plus'
                )
                
                count += 1
                print(f"成功添加作业: {new_assignment.title} (ID: {new_assignment.id})")
            except Exception as e:
                db.session.rollback()
                print(f"添加作业 {assignment_data['title']} 失败: {str(e)}")
        
        print(f"\n批量添加完成，成功添加了 {count} 个新作业题目")


if __name__ == "__main__":
    add_assignments() 